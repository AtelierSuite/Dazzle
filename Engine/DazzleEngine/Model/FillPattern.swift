import Foundation

extension Fill {
    /// `a:pattFill`: one of DrawingML's preset two-colour patterns, an
    /// eight-by-eight grid of foreground and background cells repeated
    /// across the area.
    public struct Pattern: Equatable, Hashable, Sendable {
        /// The `prst` name, such as `pct25`, `ltDnDiag` or `smCheck`. A name
        /// Dazzle does not know is kept as it is, and drawn as `pct50`.
        public var preset: String
        public var foreground: DrawingColor
        public var background: DrawingColor

        public init(preset: String, foreground: DrawingColor = .rgb(0x000000), background: DrawingColor = .rgb(0xFFFFFF)) {
            self.preset = preset
            self.foreground = foreground
            self.background = background
        }

        public init(element: XMLElement) {
            // Without colours of its own, a pattern is black on white.
            preset = element.attribute("prst") ?? "pct5"
            foreground = DrawingColor.first(in: element.firstChild(named: "fgClr")) ?? .rgb(0x000000)
            background = DrawingColor.first(in: element.firstChild(named: "bgClr")) ?? .rgb(0xFFFFFF)
        }

        public var xml: String {
            "<a:pattFill prst=\"\(preset)\"><a:fgClr>\(foreground.xml)</a:fgClr><a:bgClr>\(background.xml)</a:bgClr></a:pattFill>"
        }

        /// The pattern's eight rows, top first, each a byte whose bits are
        /// its cells, the highest bit leftmost; a set bit is foreground.
        public var rows: [UInt8] { Self.presets[preset] ?? Self.presets["pct50"] ?? [] }

        /// Whether the cell `column` across and `row` down is foreground.
        public func isForeground(column: Int, row: Int) -> Bool {
            let rows = rows
            guard !rows.isEmpty else { return false }
            let bits = rows[((row % 8) + 8) % 8]
            return bits & (0x80 >> UInt8(((column % 8) + 8) % 8)) != 0
        }

